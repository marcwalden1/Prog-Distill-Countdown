"""Gemma-270M ID-vs-OOD trajectories, sourced from the analysis CSV.

Data note (2026-07-13): the CSV (analysis_data/gemma270m_pareto_eval_progression.csv)
is regenerated by scripts/regen_gemma_pareto_csv.py from the FULL-set .scores of the
4 gemma distill/progdistill+GRPO runs under results_sdholakia/ (cap removed; see
research_logs/2026-07-13_fix-maxprompts-cap-fullset-regen.md). Regenerate the CSV
before running this if the scores change.

Four figures (one per metric column x OOD set):
  figures/gemma-3-270m/id_vs_ood_pass1_n5.png    (mean@1,  n=5)
  figures/gemma-3-270m/id_vs_ood_pass1_n6.png    (mean@1,  n=6)
  figures/gemma-3-270m/id_vs_ood_pass32_n5.png   (mean@32, n=5)
  figures/gemma-3-270m/id_vs_ood_pass32_n6.png   (mean@32, n=6)

Each figure is a single panel. Axes: in-distribution (balanced, n=3,4) on x vs
OOD (n=5 or n=6) on y, one marker per evaluated checkpoint, connected in step
order (open circle = first step, star = last). One trajectory per run
(distill/progdistill x GRPO kl3e-3/kl3e-4), colors matching
plot_gemma_hparam_lines.py.

Note: the CSV stores mean@1 / mean@32 (raw compute_score averages), NOT the
pass@1 / pass@32 (Chen et al. estimator) that scripts/plot/plot_id_vs_ood_*.py compute
from the eval JSONs. The output filenames use "pass1"/"pass32" as requested, but
the plotted quantity is mean@k.

Usage: python3 scripts/plot/plot_id_vs_ood_gemma_csv.py
"""

import csv
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

CSV = "analysis_data/gemma270m_pareto_eval_progression.csv"

# (label, method, kl, color) -- palette matches plot_gemma_hparam_lines.py.
RUNS = [
    ("distill kl3e-3",     "distill",     "3e-3", "#1c5cab"),
    ("distill kl3e-4",     "distill",     "3e-4", "#86b6ef"),
    ("progdistill kl3e-3", "progdistill", "3e-3", "#b45309"),
    ("progdistill kl3e-4", "progdistill", "3e-4", "#f0a04b"),
]
# (dataset, axis label, filename tag)
OOD = [("balanced5", "n=5", "n5"), ("balanced6", "n=6", "n6")]
# (metric name for labels, CSV column, filename tag)
METRICS = [
    ("mean@1",  "mean_at_1",  "pass1"),
    ("mean@32", "mean_at_32", "pass32"),
]
FIGURES_DIR = "figures/gemma-3-270m"
plt.rcParams.update({"font.size": 13})


def load_rows():
    with open(CSV) as f:
        return list(csv.DictReader(f))


def by_step(rows, method, kl, ds, col):
    """{step: value} for one run/dataset/metric column."""
    return {int(r["step"]): float(r[col])
            for r in rows
            if r["method"] == method and r["grpo_kl"] == kl
            and r["dataset"] == ds}


def make_figure(rows, metric_name, col, metric_tag, ood_ds, ood_label, ood_tag):
    fig, ax = plt.subplots(figsize=(7, 6))
    for lbl, method, kl, color in RUNS:
        id_by = by_step(rows, method, kl, "balanced", col)
        ood_by = by_step(rows, method, kl, ood_ds, col)
        steps = sorted(set(id_by) & set(ood_by))
        if not steps:
            continue
        xs = [id_by[s] for s in steps]
        ys = [ood_by[s] for s in steps]
        ax.plot(xs, ys, "-", color=color, alpha=0.55, linewidth=2, zorder=1)
        ax.scatter(xs, ys, s=40, color=color, label=lbl, zorder=2)
        ax.scatter([xs[0]], [ys[0]], s=120, facecolors="none",
                   edgecolors=color, linewidths=1.8, zorder=3)
        ax.scatter([xs[-1]], [ys[-1]], s=190, marker="*", color=color,
                   edgecolors="#0b0b0b", linewidths=0.5, zorder=4)
        for s, x, y in zip(steps, xs, ys):
            ax.annotate(str(s), (x, y), fontsize=6.5, color="#52514e",
                        xytext=(3, 3), textcoords="offset points")
    ax.set_xlabel(f"ID {metric_name} (n=3,4)")
    ax.set_ylabel(f"OOD {metric_name} ({ood_label})")
    ax.grid(True, alpha=0.3, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=11, frameon=False, loc="best",
              title="○ first step   ★ last step", title_fontsize=10)
    fig.tight_layout()
    out = os.path.join(FIGURES_DIR,
                       f"id_vs_ood_{metric_tag}_{ood_tag}_lr1e-6.png")
    fig.savefig(out, dpi=200)
    plt.close(fig)
    print(f"wrote {out}")


def main():
    os.makedirs(FIGURES_DIR, exist_ok=True)
    rows = load_rows()
    for metric_name, col, metric_tag in METRICS:
        for ood_ds, ood_label, ood_tag in OOD:
            make_figure(rows, metric_name, col, metric_tag,
                        ood_ds, ood_label, ood_tag)


if __name__ == "__main__":
    main()
